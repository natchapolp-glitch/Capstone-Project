import fs from 'node:fs/promises';
import path from 'node:path';
import {FileBlob,PresentationFile} from 'file:///C:/Users/NATCHAPOL/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/@oai/artifact-tool/dist/artifact_tool.mjs';
const root=process.cwd(), output=path.join(root,'PRESENTATION_READY_2026-10-26');
const build=path.join(root,'.codex-finalizer/recorded-demo-v3');
await fs.mkdir(build,{recursive:true});
const script=await fs.readFile(path.join(output,'SCRIPT_10_MIN_REVIEWED_v3.md'),'utf8');
const section=[...script.matchAll(/^### (\d+) — ([^\n]+)\n([\s\S]*?)(?=^### |^## |$(?![\s\S]))/gm)].find(s=>s[1]==='18');
if(!section)throw Error('Missing slide 18 script');
const source=path.join(output,'Ass5_10MIN_REVIEWED_v2_2026-10-26.pptx');
const deck=await PresentationFile.importPptx(await FileBlob.load(source));
const inspection=await deck.inspect({kind:'slide,textbox,table,notes,layout',maxChars:500000});
await fs.writeFile(path.join(build,'source-inspection.json'),JSON.stringify(inspection.records,null,2));
const previous=JSON.parse(await fs.readFile(path.join(root,'.codex-finalizer/review-complete-2026-10-26/source_content.json'),'utf8'));
const note=`ณัชพล | หน้า 18 | ${section[2]}\n\nบทพูดหลักในเวลา 10 นาที\n${section[3].trim()}\n\nรายละเอียดสำหรับตอบคำถาม ไม่อ่านทั้งหมดระหว่างพรี\n${previous[17].original_notes}`;
deck.slides.items[17].speakerNotes.text=note;
await fs.writeFile(path.join(build,'expected-note-18.txt'),note);
await (await PresentationFile.exportPptx(deck)).save(path.join(build,'artifact-notes.pptx'));
console.log('Authored slide 18 notes for recorded live-inference demo');
